let currentLang = 'zh';

function setLang(lang) {
  currentLang = lang === 'en' ? 'en' : 'zh';
  document.documentElement.lang = currentLang === 'en' ? 'en' : 'zh-CN';
  return currentLang;
}

function currentLangCode() {
  return currentLang;
}

/* 当前语言是否有这条文案（用于可扩展模块的兜底，如组件名称） */
function i18nHas(key) {
  const dict = I18N[currentLang] || I18N.zh;
  return dict[key] != null || I18N.zh[key] != null;
}

/* 同一条文案的所有语言版本（用于识别历史数据里的默认标题等） */
function i18nAll(key) {
  return Object.keys(I18N)
    .map((lang) => I18N[lang][key])
    .filter((v) => v != null);
}

/* 取文案：缺失时回退中文，再回退 key 本身；支持 {name} 占位 */
function i18n(key, vars) {
  const dict = I18N[currentLang] || I18N.zh;
  let text = dict[key];
  if (text == null) text = I18N.zh[key];
  if (text == null) return key;
  if (vars) {
    Object.keys(vars).forEach((k) => {
      text = text.split('{' + k + '}').join(String(vars[k]));
    });
  }
  return text;
}

/* 只替换文本节点，保留元素内部的装饰节点（例如折叠箭头 <i>） */
function setI18nText(el, text) {
  const textNodes = Array.prototype.filter.call(el.childNodes, (n) => n.nodeType === 3);
  if (textNodes.length) {
    textNodes[0].nodeValue = text;
    textNodes.slice(1).forEach((n) => n.remove());
    return;
  }
  el.insertBefore(document.createTextNode(text), el.firstChild);
}

/* 把 data-i18n* 属性铺到 DOM 上；root 可以是子树 */
function applyI18n(root) {
  const scope = root || document;
  scope.querySelectorAll('[data-i18n]').forEach((el) => {
    setI18nText(el, i18n(el.dataset.i18n));
  });
  scope.querySelectorAll('[data-i18n-html]').forEach((el) => {
    el.innerHTML = i18n(el.dataset.i18nHtml);
  });
  scope.querySelectorAll('[data-i18n-ph]').forEach((el) => {
    el.setAttribute('placeholder', i18n(el.dataset.i18nPh));
  });
  scope.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.setAttribute('title', i18n(el.dataset.i18nTitle));
  });
  scope.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    el.setAttribute('aria-label', i18n(el.dataset.i18nAria));
  });
  document.title = i18n('app.title');
}

/* 切换语言并立即把静态文案铺到页面上 */
function applyLanguage(lang) {
  const code = setLang(lang);
  applyI18n(document);
  return code;
}
